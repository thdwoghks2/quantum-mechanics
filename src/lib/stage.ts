export function stageOf(n: number): LessonStage | undefined {
  return LESSON_STAGE[n];
}

export function stageInfo(id: StageId): Stage {
  return STAGES.find((s) => s.id === id)!;
}

/** "고등학교 「물리학」 「빛과 물질」에서 배우는 내용"처럼 한 줄로 쓴다. */
export function stageLine(ls: LessonStage): string {
  const s = stageInfo(ls.stage);
  if (ls.unit) {
    const where =
      ls.stage === 'm'
        ? `중학교 과학 「${ls.unit}」`
        : `${ls.stage === 'h1' ? '고1' : '고등학교'} 「${ls.subject}」 「${ls.unit}」`;
    return ls.note ? `${where}에서 이어지는 ${ls.note}` : `${where}에서 배우는 내용`;
  }
  if (ls.note) return ls.stage === 'g' ? ls.note : `${ls.note}에서 다루는 내용`;
  return s.name;
}

/** 여러 강을 묶은 범위의 단계 (부 목록에서 "중학교 ~ 고등학교"처럼). */
export function stageRange(numbers: number[]): string {
  const idx = numbers
    .map((n) => LESSON_STAGE[n])
    .filter((x): x is LessonStage => !!x)
    .map((x) => STAGES.findIndex((s) => s.id === x.stage));
  if (!idx.length) return '';
  const lo = STAGES[Math.min(...idx)]!.zone;
  const hi = STAGES[Math.max(...idx)]!.zone;
  return lo === hi ? lo : `${lo} ~ ${hi}`;
}
